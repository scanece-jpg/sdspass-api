def _cls_flam_liq(fp: float, bp: Optional[float]) -> Optional[Dict]:
    if fp < 23 and (bp is None or bp <= 35):
        return {'h': 'H224', 'cat': 1, 'h_class': 'Flam. Liq. 1', 'signal': 'Danger'}
    if fp < 23:
        return {'h': 'H225', 'cat': 2, 'h_class': 'Flam. Liq. 2', 'signal': 'Danger'}
    if 23 <= fp <= 60:
        return {'h': 'H226', 'cat': 3, 'h_class': 'Flam. Liq. 3', 'signal': 'Warning'}
    return None


def _calc_flam_liq(comps: List[Dict], user_fp=None) -> Dict:
    DECLARED_FALLBACK = {
        'H224': {'fp': -20, 'bp': 25},
        'H225': {'fp':  15, 'bp': 80},
        'H226': {'fp':  40, 'bp': 120},
    }

    if user_fp is not None:
        # Kullanıcı FP girmiş
        theo_bp = None
        for c in comps:
            cas = (c.get('cas') or c.get('cas_no') or '').strip()
            w   = float(c.get('concMax') or c.get('conc') or 0)
            bp  = BP_DB.get(cas, 'MISSING')
            if bp != 'MISSING' and bp is not None and w >= 1:
                if theo_bp is None or bp < theo_bp:
                    theo_bp = bp
        effective_bp = theo_bp if theo_bp is not None else (100 if user_fp < 23 else None)
        return {'result': _cls_flam_liq(user_fp, effective_bp),
                'source': f'Kullanıcı girişi ({user_fp}°C)', 'fp': user_fp}

    # CLP §2.6.4.2 — su seyreltme etkisi:
    # Su (CAS 7732-18-5) >= %50 olan karışımlarda yanıcı bileşenin FP'si
    # doğrudan kullanılamaz; karışımın gerçek FP'si çok daha yüksek olur.
    # Bu durumda kullanıcıdan ölçülmüş FP istenir.
    _water_conc = sum(
        float(c.get('concMax') or c.get('conc') or 0)
        for c in comps
        if (c.get('cas') or c.get('cas_no') or '').strip() == '7732-18-5'
    )
    _high_water = _water_conc >= 50.0

    cat_sum = {1: 0.0, 2: 0.0, 3: 0.0}
    cat_triggers = {1: [], 2: [], 3: []}
    cat_fp = {1: None, 2: None, 3: None}

    for c in comps:
        cas  = (c.get('cas') or c.get('cas_no') or '').strip()
        conc = float(c.get('concMax') or c.get('conc') or 0)
        fp   = FP_DB.get(cas, 'MISSING')
        bp   = None
        estimated = False

        if fp == 'MISSING' and conc > 0:
            hazard_codes = [(h.get('h_code') or '').replace('*','').strip()[:4]
                            for h in (c.get('hazards') or [])]
            decl_h = next((h for h in hazard_codes if h in DECLARED_FALLBACK), None)
            if decl_h:
                fp        = DECLARED_FALLBACK[decl_h]['fp']
                bp        = DECLARED_FALLBACK[decl_h]['bp']
                estimated = True

        if fp is None or fp == 'MISSING' or fp >= 60:
            continue
        if not estimated:
            bp_val = BP_DB.get(cas, 'MISSING')
            bp = None if bp_val == 'MISSING' else bp_val

        cls = _cls_flam_liq(fp, bp)
        if not cls:
            continue
        cat = cls['cat']
        cat_sum[cat] += conc
        if cat_fp[cat] is None or fp < cat_fp[cat]:
            cat_fp[cat] = fp
        cat_triggers[cat].append({'cas': cas, 'name': c.get('name') or cas,
                                   'conc': conc, 'fp': fp, 'estimated': estimated})

    def trig_src(t):
        return f"{t['name']} (%{t['conc']}, FP={t['fp']}°C{'  tahmini' if t['estimated'] else ''})"

    sum1   = cat_sum[1]
    sum12  = cat_sum[1] + cat_sum[2]
    sum123 = cat_sum[1] + cat_sum[2] + cat_sum[3]

    # Kullanıcı FP girmediğinde bileşen-kategori toplamı tarama yöntemi olarak kullanılır.
    # CLP Annex I §2.6.4 resmi yöntemi karışımın ölçülen/hesaplanan FP/BP'sine dayanır;
    # bu yöntem §2.6.4.2 kapsamında muhafazakâr bir tahmini yaklaşımdır.
    _screening = True
    _water_note = (
        f'⚠ Su içeriği %{_water_conc:.0f} ≥ %50 — saf bileşen FP değerleri karışım FP\'sini '
        'doğru yansıtmaz (su seyreltme etkisi). Ölçülmüş karışım FP\'si girilmesi önerilir (CLP §2.6.4.2).'
        if _high_water else None
    )
    if sum1 >= 1:
        src = ' + '.join(trig_src(t) for t in cat_triggers[1])
        return {'result': {'h':'H224','cat':1,'h_class':'Flam. Liq. 1','signal':'Danger'},
                'source': src, 'fp': cat_fp[1], 'screening': _screening,
                'water_dilution_warning': _water_note}
    if sum12 >= 1:
        trigs = cat_triggers[1] + cat_triggers[2]
        fps   = [cat_fp[k] for k in (1,2) if cat_fp[k] is not None]
        src   = ' + '.join(trig_src(t) for t in trigs)
        return {'result': {'h':'H225','cat':2,'h_class':'Flam. Liq. 2','signal':'Danger'},
                'source': src, 'fp': min(fps) if fps else None, 'screening': _screening,
                'water_dilution_warning': _water_note}
    if sum123 >= 10:
        all_trigs = cat_triggers[1] + cat_triggers[2] + cat_triggers[3]
        all_fps   = [cat_fp[k] for k in (1,2,3) if cat_fp[k] is not None]
        src       = ' + '.join(trig_src(t) for t in all_trigs)
        return {'result': {'h':'H226','cat':3,'h_class':'Flam. Liq. 3','signal':'Warning'},
                'source': src, 'fp': min(all_fps) if all_fps else None, 'screening': _screening,
                'water_dilution_warning': _water_note}
    return {'result': None, 'source': None, 'fp': None, 'screening': _screening,
            'water_dilution_warning': _water_note}


def _calc_flam_aerosol(comps: List[Dict], user_fp=None,
                        aerosol_flam_pct=None, aerosol_hoc=None) -> Optional[Dict]:
    """
    CLP Ek-I §2.3 — Aerosol yanıcılık sınıflandırması.
    aerosol_flam_pct: Kullanıcı beyanı — yanıcı içerik % (w/w).
      ≥ 85% VE yanma ısısı ≥30 kJ/g → H222 Kat.1
      ≥ 85% ama yanma ısısı <30 kJ/g → H223 Kat.2
      1–85% → H223 Kat.2
      <  1% → None (sadece H229)
    Girilmemişse parlama noktası tabanlı yöntem kullanılır:
      H222 Kat.1: FP < 23°C bileşen ≥ %1
      H223 Kat.2: FP 23-60°C bileşen ≥ %1
    """
    if aerosol_flam_pct is not None:
        pct = float(aerosol_flam_pct)
        if pct >= 85:
            hoc = float(aerosol_hoc) if aerosol_hoc is not None else None
            if hoc is not None and hoc >= 30:
                return {'h': 'H222', 'h_class': 'Flam. Aerosol 1', 'signal': 'Danger',
                        'source': (f'Kullanıcı beyanı: yanıcı içerik %{pct:.0f}, '
                                   f'yanma ısısı {hoc} kJ/g (CLP Ek-I §2.3.3.1)')}
            elif hoc is None:
                return {'h': 'H222', 'h_class': 'Flam. Aerosol 1', 'signal': 'Danger',
                        'source': (f'Kullanıcı beyanı: yanıcı içerik %{pct:.0f} — '
                                   'H222 Cat.1; yanma ısısı ≥30 kJ/g doğrulanmalı (CLP Ek-I §2.3.3.1)')}
            else:
                return {'h': 'H223', 'h_class': 'Flam. Aerosol 2', 'signal': 'Warning',
                        'source': (f'Kullanıcı beyanı: yanıcı içerik %{pct:.0f}, '
                                   f'yanma ısısı {hoc} kJ/g <30 → Kat.2 (CLP Ek-I §2.3.3.1)')}
        if pct >= 1:
            return {'h': 'H223', 'h_class': 'Flam. Aerosol 2', 'signal': 'Warning',
                    'source': f'Kullanıcı beyanı: yanıcı içerik %{pct:.0f} (CLP Ek-I §2.3.3.1)'}
        return None
    DECLARED_FALLBACK = {
        'H224': -20, 'H225': 15, 'H226': 40,
    }
    sum_cat1, sum_cat2 = 0.0, 0.0
    triggers_cat1: list = []
    triggers_cat2: list = []

    for c in comps:
        cas  = (c.get('cas') or c.get('cas_no') or '').strip()
        conc = float(c.get('concMax') or c.get('conc') or 0)
        if conc <= 0:
            continue

        fp = user_fp if user_fp is not None else FP_DB.get(cas, 'MISSING')

        if fp == 'MISSING':
            hazard_codes = [(h.get('h_code') or '').replace('*','').strip()[:4]
                            for h in (c.get('hazards') or [])]
            decl_h = next((h for h in hazard_codes if h in DECLARED_FALLBACK), None)
            if decl_h:
                fp = DECLARED_FALLBACK[decl_h]

        if fp is None or fp == 'MISSING' or fp >= 60:
            continue

        label = f"{c.get('name') or cas} (%{conc:.0f}, FP={fp}°C)"
        if fp < 23:
            sum_cat1 += conc
            triggers_cat1.append(label)
        else:
            sum_cat2 += conc
            triggers_cat2.append(label)

    _warn = {
        'code': 'AEROSOL_FP_FALLBACK',
        'message': (
            'Aerosol yanıcılık sınıflandırması onaylı aerosol testi veya beyan edilen '
            'yanıcı içerik yüzdesi (aerosol_flam_pct) yerine bileşen parlama noktaları '
            'üzerinden tahmin edilmiştir. CLP Ek-I §2.3 uyarınca doğrulama gerekir.'
        ),
        'message_en': (
            'Aerosol flammability classification is estimated from component flash points '
            'rather than an approved aerosol test or declared flammable content percentage. '
            'Verification per CLP Annex I §2.3 is required.'
        ),
    }
    if sum_cat1 >= 1:
        return {'h': 'H222', 'h_class': 'Flam. Aerosol 1', 'signal': 'Danger',
                'source': ', '.join(triggers_cat1), 'warning': _warn}
    if sum_cat2 >= 1:
        return {'h': 'H223', 'h_class': 'Flam. Aerosol 2', 'signal': 'Warning',
                'source': ', '.join(triggers_cat2), 'warning': _warn}
    return None


def _calc_asp_tox(comps: List[Dict], test_data: Dict = None) -> Dict:
    kin_visc = None
    if test_data:
        v = test_data.get('viscosity')
        if v is not None:
            try:
                kin_visc = float(v)
            except (ValueError, TypeError):
                pass

    if kin_visc is not None and kin_visc > 20.5:
        return {'result': None,
                'source': f'Kinematik viskozite {kin_visc} mm²/s > 20,5 mm²/s — H304 uygulanmaz',
                'total': 0, 'viscosity_excluded': True}

    total, triggers = 0.0, []
    for c in comps:
        cas  = (c.get('cas') or c.get('cas_no') or '').strip()
        conc = float(c.get('concMax') or c.get('conc') or 0)
        in_list   = cas in ASP_CAS
        has_class = any((h.get('h_class') or '') == 'Asp. Tox. 1'
                        for h in (c.get('hazards') or []))
        if (in_list or has_class) and conc > 0:
            triggers.append({'cas': cas, 'name': c.get('name') or cas, 'conc': conc})
            total += conc

    if total >= 10:
        visc_note = '' if kin_visc is not None else ' (viskozite girilmedi — doğrulayın)'
        src = ', '.join(f"{t['name']} (%{t['conc']})" for t in triggers) + visc_note
        return {'result': {'h':'H304','h_class':'Asp. Tox. 1','signal':'Danger'},
                'source': src, 'total': total}
    return {'result': None, 'source': None, 'total': total}


def _calc_flam_gas(comps: List[Dict]) -> Dict:
    triggers = []
    for c in comps:
        cas  = (c.get('cas') or c.get('cas_no') or '').strip()
        conc = float(c.get('concMax') or c.get('conc') or 0)
        if conc < 1.0:
            continue
        has_h232 = any((h.get('h_code') or '').replace('*','').strip()[:4] == 'H232'
                       for h in (c.get('hazards') or []))
        if has_h232 or cas in PYRO_GAS_CAS:
            triggers.append({'cas': cas, 'name': c.get('name') or cas, 'conc': conc})

    if triggers:
        src = ', '.join(f"{t['name']} (%{t['conc']})" for t in triggers)
        return {'result_h220': {'h':'H220','h_class':'Flam. Gas 1A','signal':'Danger'},
                'result_h232': {'h':'H232','h_class':'Flam. Gas 1A — Pirofor','signal':'Danger'},
                'source': src}
    return {'result_h220': None, 'result_h232': None, 'source': None}


# ── ANA HESAP FONKSİYONU ─────────────────────────────────────────────────────

def calculate(comps: List[Dict], form: str = 'liquid',
              user_fp=None, test_data: Dict = None,
              form_sub: str = '') -> Dict:
    """
    Fiziksel tehlike sınıflandırması + teorik fiziksel özellikler hesapla.

    Returns:
        {
          'results': [...],    # tüm tehlike sonuçları
          'primary': [...],    # ana tehlikeler
          'extra':   [...],    # ek tehlikeler
          'warnings': [...],
          'theo_props': {...}  # teorik fiziksel özellikler
        }
    """
    if test_data is None:
        test_data = {}

    primary, extra, warnings = [], [], []

    fl = {'result': None, 'source': None, 'fp': None}
    if form in ('liquid', 'paste'):
        fl = _calc_flam_liq(comps, user_fp)
        if fl.get('water_dilution_warning'):
            warnings.append(fl['water_dilution_warning'])
        if fl['result']:
            _flam_cutoff = {
                'H224': '≥ %1 Cat.1 yanıcı sıvı bileşen (CLP Ek-I Tablo 2.6)',
                'H225': '≥ %1 Cat.1+2 yanıcı sıvı bileşen (CLP Ek-I Tablo 2.6)',
                'H226': '≥ %10 yanıcı sıvı bileşen (CLP Ek-I Tablo 2.6)',
            }.get(fl['result']['h'], 'Yanıcı sıvı — CLP Ek-I Tablo 2.6')
            primary.append({'type': 'flam_liq', **fl['result'],
                            'source': fl['source'], 'fp': fl['fp'],
                            'cutoff_used': _flam_cutoff})

    if form == 'aerosol':
        fa = _calc_flam_aerosol(comps, user_fp,
                                aerosol_flam_pct=test_data.get('aerosol_flam_pct'),
                                aerosol_hoc=test_data.get('aerosol_hoc'))
        if fa:
            if fa.get('warning'):
                warnings.append(fa.pop('warning'))
            primary.append({'type': 'flam_aerosol', **fa,
                            'cutoff_used': 'CLP Ek-I §2.3 — Aerosol yanıcılık sınıflandırması'})
        extra.append({'type': 'aerosol_press', 'h': 'H229', 'h_class': 'Aerosol 3',
                      'signal': 'Warning', 'source': 'Aerosol ürün — basınçlı kap',
                      'cutoff_used': 'CLP Ek-I §2.3 — tüm aerosollere uygulanır'})

    if form in ('liquid', 'paste'):
        # Kullanıcı viskozite girmemişse hesaplanmış değeri kullan
        _asp_test = dict(test_data)
        if _asp_test.get('viscosity') is None:
            _pre_props = calc_theo_props(comps) or {}
            _calc_visc = (_pre_props.get('viscosity') or {}).get('value')
            if _calc_visc is not None:
                _asp_test['viscosity'] = _calc_visc
        asp = _calc_asp_tox(comps, _asp_test)
        if asp['result']:
            primary.append({'type': 'asp_tox', **asp['result'],
                            'source': asp['source'], 'total': asp['total'],
                            'cutoff_used': '≥ %10 aspirasyon toksik bileşen'})
        if asp.get('viscosity_excluded'):
            warnings.append('H304: ' + asp['source'])

    if form == 'gas':
        fg = _calc_flam_gas(comps)
        if fg['result_h232']:
            _pyro_cutoff = '≥ %1 pirofor gaz bileşen'
            primary.append({'type': 'flam_gas',      **fg['result_h220'], 'source': fg['source'], 'cutoff_used': _pyro_cutoff})
            primary.append({'type': 'flam_gas_pyro', **fg['result_h232'], 'source': fg['source'], 'cutoff_used': _pyro_cutoff})

        ox_gas = [c for c in comps
                  if ((c.get('cas') or c.get('cas_no') or '').strip() in OXIDIZING_GAS_CAS
                      or any((h.get('h_code') or '').replace('*','').strip()[:4] == 'H270'
                             for h in (c.get('hazards') or [])))
                  and float(c.get('concMax') or c.get('conc') or 0) >= 1]
        if ox_gas:
            _ox_src = ', '.join(
                f"{c.get('name') or (c.get('cas') or c.get('cas_no') or '')} "
                f"(%{float(c.get('concMax') or c.get('conc') or 0):.0f})" for c in ox_gas)
            extra.append({'type': 'ox_gas', 'h': 'H270', 'h_class': 'Ox. Gas 1',
                          'signal': 'Danger', 'source': _ox_src,
                          'cutoff_used': '≥ %1 oksitleyici gaz bileşen (CLP Ek-I §2.4)'})

        # H280/H281 — Basınçlı kap (CLP Ek-I §2.5, Tablo 2.5.1)
        # Gaz formu = ≥200 kPa gauge ambalaj → H280 zorunlu (ambalaj özelliği, içerikten bağımsız)
        is_cryo = bool(test_data.get('cryo_gas'))
        extra.append({
            'type':        'press_gas',
            'h':           'H281' if is_cryo else 'H280',
            'h_class':     'Press. Gas (Refrigerated liq.)' if is_cryo else 'Press. Gas (Compressed/Liquefied/Dissolved)',
            'signal':      'Warning',
            'source':      'Gaz formu — CLP Ek-I §2.5 Tablo 2.5.1',
            'cutoff_used': 'Gaz formundaki tüm ürünlere uygulanır (≥200 kPa gauge @20°C)',
        })

    if form in ('solid', 'powder'):
        fs = [c for c in comps
              if (c.get('cas') or c.get('cas_no') or '').strip() in FLAM_SOL_CAS
              and float(c.get('concMax') or c.get('conc') or 0) >= 1]
        if fs:
            _fs_src = ', '.join(f"{c.get('name') or c.get('cas','')} (%{float(c.get('concMax') or c.get('conc') or 0):.0f})" for c in fs)
            extra.append({'type': 'flam_sol', 'h': 'H228', 'h_class': 'Flam. Sol. 2',
                          'signal': 'Warning', 'source': _fs_src,
                          'cutoff_used': '≥ %1 yanıcı katı bileşen (CLP Ek-I Tablo 2.7)'})

        # H228 validator uyarısı — katı/toz formda otomatik atama yapılmaz (test zorunlu)
        warnings.append(
            'Katı/toz form: Yanıcı katı sınıflandırması (H228) UN Test N.1 test verisine dayanır '
            '(CLP Ek-I §2.7) — motor bileşen H kodundan karışım H228 ataması yapmaz. '
            'Bileşen Ek-VI kaydında H228 varsa CLP motoru tarafından değerlendirilir.'
        )

        # Toz patlama uyarısı — powder formu veya powder_fine/powder_nano alt kategorisi
        if form == 'powder' or form_sub in ('powder_fine', 'powder_nano'):
            warnings.append(
                'Toz patlama riski: İnce toz (<500 µm) organik veya metal tozları için '
                'toz-hava bulutu patlama riski değerlendirilmeli (ATEX 2014/34/AB; '
                'EN 14034 Kst/Pmax testi önerilir). CLP toz patlamasını ayrı bir tehlike '
                'sınıfı olarak sınıflandırmaz; SDS Bölüm 7 ve 8\'de belirtilmesi zorunludur.'
            )

        # Nano malzeme genel uyarısı — TiO2 dışı nano boyutlu bileşenler
        if form_sub == 'powder_nano':
            warnings.append(
                'Nano boyutlu toz (< 1 µm): CLP 2021/2030 sayılı Tüzük TiO2 nano için özel '
                'EUH212 gerektirir. Diğer nano malzemeler için: (1) bulk formdaki CLP '
                'sınıflandırması başlangıç noktasıdır, (2) nano spesifik toksikoloji '
                'verileri mevcutsa SDS Bölüm 11\'e eklenmeli, (3) REACH nano kayıt '
                'yükümlülükleri kontrol edilmeli (ECHA Nanomaterials guidance, R.7c).'
            )

        ox_sol_triggers = []
        ox_sol_has_h271 = False
        for c in comps:
            cas  = (c.get('cas') or c.get('cas_no') or '').strip()
            conc = float(c.get('concMax') or c.get('conc') or 0)
            comp_h = {(h.get('h_code') or '').replace('*','').strip()[:4]
                      for h in (c.get('hazards') or [])}
            h_match = comp_h & {'H271', 'H272'}
            in_list = cas in OXIDIZING_SOLID_CAS
            if (in_list or h_match) and conc >= OXIDIZING_SOLID_CUTOFFS['H272']:
                ox_sol_triggers.append({'name': c.get('name') or cas, 'conc': conc})
                if 'H271' in h_match:
                    ox_sol_has_h271 = True
        if ox_sol_triggers:
            _ox_h   = 'H271' if ox_sol_has_h271 else 'H272'
            _ox_cls = 'Ox. Sol. 1' if ox_sol_has_h271 else 'Ox. Sol. 2'
            _ox_sig = 'Danger'  if ox_sol_has_h271 else 'Warning'
            _ox_src = ', '.join(f"{t['name']} (%{t['conc']:.0f})" for t in ox_sol_triggers)
            extra.append({'type': 'oxidizing_solid', 'h': _ox_h, 'h_class': _ox_cls,
                          'signal': _ox_sig, 'source': _ox_src,
                          'cutoff_used': f'Bileşen verisi ≥ %{OXIDIZING_SOLID_CUTOFFS[_ox_h]:.0f} — karışım test verisi mevcut değil (CLP §2.13.4.2 bridging prensibi)'})

    if form in ('liquid', 'paste'):
        # CLP Ek-I Tablo 2.13.1 — oksitleyici sıvı karışım sınıflandırması
        # Bileşenlerden kategori belirleme: (1) CAS sözlüğünden, (2) H-kod chip'inden
        def _ox_liq_cat(c) -> int:
            cas = (c.get('cas') or c.get('cas_no') or '').strip()
            if cas in OXIDIZING_LIQ_CAS:
                return OXIDIZING_LIQ_CAS[cas]
            h_codes = {(h.get('h_code') or '').replace('*','').strip()[:4]
                       for h in (c.get('hazards') or [])}
            if 'H271' in h_codes:
                return 1
            if 'H272' in h_codes:
                return 2  # H272 = Ox.Liq.2 veya 3; muhafazakar olarak 2 kabul et
            return 0

        ox_liq_triggers: list = []
        for c in comps:
            cat = _ox_liq_cat(c)
            if not cat:
                continue
            conc = float(c.get('concMax') or c.get('conc') or 0)
            if conc > 0:
                ox_liq_triggers.append({
                    'name': c.get('name') or c.get('cas', ''),
                    'conc': conc, 'cat': cat,
                })

        if ox_liq_triggers:
            # Toplama yöntemi (CLP Tablo 2.13.1)
            sum_cat1     = sum(t['conc'] for t in ox_liq_triggers if t['cat'] == 1)
            sum_cat1_2   = sum(t['conc'] for t in ox_liq_triggers if t['cat'] in (1, 2))
            sum_cat1_2_3 = sum(t['conc'] for t in ox_liq_triggers)

            if sum_cat1 >= 1.0:
                _ox_h, _ox_cls, _ox_sig = 'H271', 'Ox. Liq. 1', 'Danger'
            elif sum_cat1_2 >= 5.0:
                _ox_h, _ox_cls, _ox_sig = 'H272', 'Ox. Liq. 2', 'Warning'
            elif sum_cat1_2_3 >= 10.0:
                _ox_h, _ox_cls, _ox_sig = 'H272', 'Ox. Liq. 3', 'Warning'
            else:
                _ox_h = None

            if _ox_h:
                _ox_src = ', '.join(
                    f"{t['name']} (%{t['conc']:.0f}, Kat.{t['cat']})"
                    for t in ox_liq_triggers
                )
                extra.append({'type': 'oxidizing', 'h': _ox_h, 'h_class': _ox_cls,
                              'signal': _ox_sig, 'source': _ox_src,
                              'cutoff_used': (
                                  f'CLP Tablo 2.13.1 toplama yöntemi — '
                                  f'Kat.1 toplamı %{sum_cat1:.1f}, '
                                  f'Kat.1+2 toplamı %{sum_cat1_2:.1f}, '
                                  f'Kat.1+2+3 toplamı %{sum_cat1_2_3:.1f}'
                              )})

    # Özel fiziksel tehlike muafiyet/manuel giriş (kullanıcı beyanı)
    _MANUAL_H_MAP = {
        'water_reactive':  {'H260': ('H260', 'Water React. 1',   'Danger'),
                            'H261': ('H261', 'Water React. 2/3', 'Warning')},
        'pyrophoric':      {'H250': ('H250', 'Pyr. Liq./Sol. 1', 'Danger')},
        'self_heating':    {'H251': ('H251', 'Self-heat. 1',     'Danger'),
                            'H252': ('H252', 'Self-heat. 2',     'Warning')},
        'metal_corrosive': {'H290': ('H290', 'Met. Corr. 1',    'Warning')},
        'organic_peroxide':{'H240': ('H240', 'Org. Perox. Type A', 'Danger'),
                            'H241': ('H241', 'Org. Perox. Type B', 'Danger'),
                            'H242': ('H242', 'Org. Perox. Type C/D/E/F', 'Warning')},
    }
    for field, h_map in _MANUAL_H_MAP.items():
        val = (test_data.get(field) or '').strip()
        if val and val != 'na' and val in h_map:
            h, h_class, signal = h_map[val]
            extra.append({'type': f'manual_{field}', 'h': h, 'h_class': h_class,
                          'signal': signal, 'source': 'Kullanıcı beyanı — test sonucu',
                          'cutoff_used': 'Manuel giriş (CLP Ek-I muafiyet dışı)'})

    # Teorik fiziksel özellikler — katı/toz için yoğunluk+çözünürlük, gaz için buhar yoğunluğu
    theo_props = calc_theo_props(comps) or {}

    # Test verisi varsa üzerine yaz
    if test_data:
        _apply_test_data(theo_props, test_data)

    # Parlama noktasını ekle
    if test_data.get('flash_point') is not None:
        theo_props['flash_point'] = {
            'value': test_data['flash_point'], 'measured': True,
            'method': 'Kullanıcı girişi', 'standard': 'ISO 2719 / ASTM D93',
        }
    elif fl['fp'] is not None:
        theo_props['flash_point'] = {
            'value': fl['fp'], 'measured': False,
            'method': fl['source'] or 'DB sorgusu', 'standard': 'CLP Annex VI / NIST',
            'note': f"Sınıflandırma: {fl['result']['h_class']} ({fl['result']['h']})" if fl['result'] else '',
        }

    return {
        'results':    primary + extra,
        'primary':    primary,
        'extra':      extra,
        'warnings':   warnings,
        'theo_props': theo_props,
    }


def _apply_test_data(props: Dict, test_data: Dict) -> None:
    """Test/ölçülen verileri teorik değerlerin üzerine yaz (in-place)."""
    def meas(value, standard, note='Test verisinden alındı.'):
        return {'value': value, 'measured': True,
                'method': 'Kullanıcı girişi (ölçülen/beyan değer)',
                'standard': standard, 'note': note, 'error': None}

    mapping = {
        'density':       ('density',       'ISO 2811 / ASTM D4052'),
        'boiling_point': ('boiling_point', 'ASTM D86 / ISO 3924'),
        'ph':            ('ph',            'ISO 4316 / ASTM E70'),
        'viscosity':     ('viscosity',     'ISO 3219 / ASTM D2196'),
        'solubility':    ('solubility',    'OECD 105'),
        'flash_point':   ('flash_point',   'ISO 2719 / ASTM D93'),
        'vapor_pressure':('vapor_pressure','Raoult Yasası / OECD 104'),
    }
    for key, (prop, std) in mapping.items():
        if test_data.get(key) is not None:
            props[prop] = meas(test_data[key], std)

    # Yalnızca kullanıcı girer; (test_key, prop_key, std)
    for test_key, prop_key, std in [
        ('appearance',  'appearance',        'REACH Ek II §9'),
        ('odor',        'odor',              'Duyusal test'),
        ('melting_point','melting_point',    'ISO 1218 / ASTM D97'),
        ('auto_ignition','auto_ignition',    'EN 14522 / ASTM E659'),
        ('decomp_temp', 'decomposition_temp','ISO 11357 / DSC'),
        ('evap_rate',   'evap_rate',         'ASTM D3539'),
        ('log_kow',     'log_kow',           'OECD 117 / 107'),
    ]:
        if test_data.get(test_key) is not None:
            props[prop_key] = meas(test_data[test_key], std)


def update_db(cas: str, props: Dict) -> None:
    """Çalışma zamanında veritabanını güncelle (PubChem verisi vb.)."""
    c = cas.strip()
    if not c:
        return
    if props.get('density') is not None:
        DENSITY_DB[c] = props['density']
    # BP: önceden tanımlı null dahil mevcut değerlerin üzerine yazma
    if props.get('boiling_point') is not None and c not in BP_DB:
        BP_DB[c] = props['boiling_point']
    # FP: aynı kural
    if 'flash_point' in props and c not in FP_DB:
        FP_DB[c] = props['flash_point']
    if props.get('vapor_pressure') is not None:
        VP_DB[c] = props['vapor_pressure']
    if props.get('viscosity') is not None:
        VISC_DB[c] = props['viscosity']
    if props.get('solubility') is not None:
        SOL_DB[c] = props['solubility']
    if props.get('mw') is not None:
        MW_DB[c] = props['mw']
    if props.get('lel') is not None:
        LEL_DB[c] = props['lel']
    if props.get('uel') is not None:
        UEL_DB[c] = props['uel']
